import type { DataProvider, GranumGridApi } from 'granum-grid';
import type { SqlColumn, SqlProvider, SqlRow, SqlSource, SqlView } from '@granum/sql';
import { DatabaseIcon } from './icons';
import { columnRows } from './parquet';
import { compact, formatCount, type DemoDataset } from './types';

/** What the open panel needs about a file's source: its revisions and how it was opened. */
export interface SqlDetails {
  source: SqlSource;
  /** The file's name, or the sample's. */
  name: string;
  /** The file's size in bytes, unknown for the sample. */
  bytes: number | null;
  sample: boolean;
  /** DuckDB's version string. */
  engine: string;
  /** Views opened on this source, newest first; their revisions are still kept. */
  views: SqlView[];
}
const details = new WeakMap<DataProvider<unknown>, SqlDetails>();
export const sqlDetails = (provider: DataProvider<unknown>) => details.get(provider);

/** A view's filter and order in a few words, for the revision list. */
export function describeView(view: SqlView) {
  const parts = [
    view.whereSql?.trim() ? `where ${view.whereSql.trim()}` : 'all rows',
    view.orderBy?.length
      ? `by ${view.orderBy.map((item) => `${item.column}${item.descending ? ' ↓' : ''}`).join(', ')}`
      : 'in file order',
  ];
  return parts.join(', ');
}

const shownColumns = (columns: readonly SqlColumn[]) => columns.slice(0, 6).map((c) => c.name);
const asColumns = (columns: readonly SqlColumn[]) =>
  columns.map((column) => ({
    name: column.name,
    type: column.type,
    numeric: column.kind === 'number',
  }));

const startProvider: DataProvider<SqlRow> = {
  id: 'sql:none',
  revision: '0',
  rowCount: 0,
  fetchRows: async () => [],
};

