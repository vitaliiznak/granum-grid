/** The dataset for one revision of an opened file or the sample. */
export function sqlDataset(provider: SqlProvider, info: SqlDetails): DemoDataset<SqlRow> {
  details.set(provider, info);
  const metric = provider.view.metric;
  const time = provider.view.timeColumn;
  const numeric = provider.columns.find((column) => column.kind === 'number');
  const text = provider.columns.find((column) => column.kind === 'text');
  const size = info.bytes === null ? 'generated in DuckDB' : `${compact(info.bytes)}B file`;
  return {
    ...fileStart,
    name: info.sample ? 'Sample requests (SQL)' : 'Your file (SQL)',
    title: info.name,
    description: `${formatCount(provider.rowCount)} rows, ${describeView(provider.view)}. DuckDB built this revision in ${formatCount(Math.round(provider.buildMs))} ms; rows are a range scan of its table, the map and summaries are exact, and search reads every row.`,
    facts: [`${formatCount(provider.columns.length)} columns`, size, `DuckDB ${info.engine}`],
    provider,
    sourceLabel: info.sample ? 'DuckDB in this tab' : 'Your file, in this tab',
    sourceNote: info.sample
      ? 'Generated by a SQL statement in this tab: deterministic, but not real traffic.'
      : 'Read in place by DuckDB in this tab and never uploaded. Its Parquet and JSON readers come from extensions.duckdb.org; reloading forgets the file.',
    bytesPerRow: info.bytes && provider.rowCount ? info.bytes / provider.rowCount : 0,
    cache: { estimateRowBytes: (row) => 64 + JSON.stringify(row).length * 2 },
    task: {
      title: 'Jump anywhere: every address is one range scan.',
      action: 'Go to the middle',
      run: (api) => api.goTo(Math.floor(provider.rowCount / 2)),
    },
    atlas: { axisLabel: time ? 'Date' : 'Row', preview: 'summary', showRange: true },
    map: {
      chapters: 'Chapters',
      profile: metric ?? 'Overview',
      tracks: 'Show extra tracks',
      explain: metric
        ? `Down follows the revision's row order. Right means a larger ${metric}; the band spans each group's smallest and largest value, the line is its mean.`
        : 'This revision has no number column for the map, so the map is a scrollbar.',
      sampling: metric
        ? 'Exact: DuckDB computes every group from every row.'
        : 'No summary is read.',
    },
    tour: [
      ...(text
        ? [
            {
              feature: 'Search',
              label: `Search ${text.name}`,
              hint: 'Plain text matches any text column, case-insensitively, across every row.',
              run: (api: GranumGridApi<unknown>) => api.openSearch(''),
            },
          ]
        : []),
      ...(numeric
        ? [
            {
              feature: 'Predicate',
              label: `Find ${numeric.name} > 0`,
              hint: 'A predicate runs as SQL with a parameter, from the current row onward.',
              run: (api: GranumGridApi<unknown>) => api.openSearch(`${numeric.name} > 0`),
            },
          ]
        : []),
      {
        feature: 'Jump',
        label: 'Jump to the last row',
        hint: 'The last row is as cheap as the first: a range scan by address.',
        run: (api) => api.goTo(Math.max(0, provider.rowCount - 1)),
      },
    ],
    ...columnRows(asColumns(provider.columns), shownColumns(provider.columns)),
  };
}
